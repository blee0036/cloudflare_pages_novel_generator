        # ②"必须跟标题"这一条不是顺手加的，它是把 32 本换规则的书压到 15 本的那把刀。
        # 允许裸 `【1】`/`（一）` 时，全库 32 本换规则里有 13 本变坏——那些书的
        # `【1】` 是**章内小节号**：带标题的章（`第一章 标题`）会被数量多出好几倍的
        # `【1】`/`【一】` 取代，有的还会切出巨型节点。要求标题之后，13 本里 12 本
        # 不再换规则，而带标题的那一类一本没少：15 本换规则的书里 14 本是
        # "几十个巨型节点 → 几百个真标题"（有的书原先只切出个位数的节点；还有一本原先靠
        # `※※※` 分场，换成了几百条 `【NNN】标题`）。
