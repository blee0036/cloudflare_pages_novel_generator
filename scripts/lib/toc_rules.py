# -*- coding: utf-8 -*-
r"""具名章节规则表（design §4.3，需求 8.1 / 8.6）。

职责：**只放数据**。这里没有扫描、没有评分、没有切分——那些在 `toc.py`（任务 17/18）。
本模块的全部产出就是 `RULES`：15 条按行匹配的规则，顺序即优先级。

## 出处与许可

匹配思路、以及"精确优先、激进靠后 + 激进规则 opt-in"的排序经验，参考
Legado（阅读 3.0）的 `assets/defaultData/txtTocRule.json`（GPL-3.0），
见 requirements.md 附录 L。**单位字的约束不是它的做法**：Legado 用后继字黑名单，
本项目改成后缀白名单，理由见下面 `_UNIT_TAIL` 那一节。

**这里没有复制它的任何一条正则，规则按本项目的架构重写。**架构差异是硬性的：
Legado 用 `Pattern.MULTILINE` 在字节缓冲块上匹配，所以它需要 `(?<=[　\s])` 一类
lookbehind 变体、以及成对的"去空白 / 不去空白"两条规则（26 条里有相当一部分是这种
同义变体）；本项目持有完整解码文本并**按行**匹配，`^[ \t\u3000]{0,4}` 一条就覆盖了
这两种情形，于是同义变体被合并，26 条收敛为 12 条；后来又按下面「按书成类的编号习惯」
那一节增补了 3 条，共 15 条。

## 输入契约（15 条规则一律相同，`toc.py` 必须照此喂数据）

规则匹配的是**去掉行终止符、其余原样保留**的单行文本，即 `str.splitlines()` 的产物：

- **不要**先 `strip()`：行首缩进由规则自己的 `^[ \t\u3000]{0,4}` 处理。这是"顶格短行"
  （第 14 条）能成立的前提——它靠 `^\S` 判断顶格，喂 `strip()` 过的行会让每一行都顶格。
- 行尾空白同样由规则处理（`[ \t\u3000\r]*$`），调用方无需 `rstrip()`。
- `\r` 被容错接受（`_PAD` 含 `\r`），所以按 `text.split('\n')` 切 CRLF 文本也不会全表失效；
  但**规范做法仍是 `splitlines()`**，别依赖这个兜底。
- 行内容不含 `\n`，故规则里的 `.` 与 `$` 语义明确：`$` 就是行尾，不需要 `re.MULTILINE`。

一句话：`rule.match(line)` 里的 `line` 是"一行原文"，不是"清洗过的标题候选"。

## 规则表本身

| # | name | 默认 | 匹配 |
| --- | --- | --- | --- |
| 1 | 标准章节 | ✅ | `第N章 标题` / `第N章`（`UNIT` 的后缀白名单在此生效）**或** `SPECIAL` 系列 |
| 2 | 卷部册集 | ✅ | `第N卷 标题` / `卷N 标题` / `上部` |
| 3 | 单位 序号 | ✅ | `章一 标题` / `段三一 标题`（单位字在前、序号在后） |
| 4 | 特殊章节 | ✅ | `SPECIAL` 系列（序章/楔子/番外…） |
| 5 | 数字 分隔符 标题 | ✅ | `001、标题` / `1. 标题` |
| 6 | 大写数字 分隔符 标题 | ✅ | `一、标题` / `二十四章 标题` |
| 7 | 大写数字 冒号 标题 | ✅ | `三：标题` |
| 8 | 拉丁章节 | ✅ | `Chapter 1` / `Part 2` / `Episode 3` / `No.4` |
| 9 | 括号装饰 | ✅ | `【第一章 标题】` / `【012】标题` / `〔三七〕标题` |
| 10 | 符号装饰 | ✅ | `☆、标题` / `★ 标题`（`decorative=True`，见下） |
| 11 | 书名 序号 | ✅ | `标题(12)` / `标题 12` |
| 12 | 分节阅读 | ✅ | `第一页` / `分节阅读-3` |
| 13 | 纯序号行 | ❌ | 整行只有一个序号：`一` / `壹` / `1` / `【一】` |
| 14 | 顶格短行 | ❌ | `^\S.{1,20}$` |
| 15 | 通用激进 | ❌ | 合并式宽松规则 |

第 1 条把 `SPECIAL` 作为一个并列分支带上（Legado 的标准章节规则也是这么写的），因为
需求 8.1 对一本书**只选一条**规则：真实的书几乎都是 `第N章` 加上独立成行的
`楔子` / `番外` / `后记`，若 `SPECIAL` 只存在于第 4 条，这些标题在选中第 1 条的书上会
整段丢失——靠前的被并进"序章 / 前言"块，靠后的被粘在末章尾部。第 4 条保留原样，
它服务的是另一类书：只有特殊标题、没有任何编号章节。

第 10 条带 `decorative=True`：它匹出来的"标题"可能整行都是装饰符号（`※※※`），
于是它在结构上必然比章节多，按命中数硬比就必然赢。约束落在择一那一层——
已经有精确规则被选中时它不许把人顶掉，见第 10 条自己的注释与 `toc.pick_rule`。

第 13、14、15 条 `enabled=False`（需求 8.6）：它们对"任何短行 / 任何序号行"都成立，
在有正常章节标记的书上必然压过精确规则。它们的用途是给确实没有标记的书兜底，
由覆盖表（任务 21）显式点名启用。第 13 条为什么必须待在这一档，见下面那一节。

顺序有意义：评分器的提前退出（需求 8.5）与取代门槛（需求 8.4）都假定靠前的规则更保守。
增删规则请改这里，`check_toc.py`（任务 27）能对同一批样本逐条跑出指标做前后对比（需求 8.12）。

## 按书成类的编号习惯（第 3、7 条与第 9 条的裸序号分支）

7681 本库逐本实测（全量扫 `public/books/*.txt.gz`，量化口径见每条规则自己的注释）发现
三类"整本书都规整、但旧表一条规则都表达不了"的编号习惯，每一类都让一本书整本失去导航：

- **单位字在前、序号在后**（第 3 条）：`段一 标题`、`章二十六 标题`。旧表的第 1 条硬要一个
  `第`，第 2 条的裸单位分支只认 卷/部/册/集/篇，`章`/`段` 无处可去。
- **大写数字 + 全角冒号**（第 7 条）：`一：标题`、`二十七：标题`。第 6 条的 `_SEP_CN`
  故意排掉 `：`（不然对话密集的书会刷爆），第 5 条认 `：` 但只接在阿拉伯数字后面。
- **括号里只有序号**（第 9 条新增的分支）：`【012】标题`、`〔三七〕标题`、
  `【一、标题】`。旧的第 7 条要求括号**里面**是 `第N<单位>` / SPECIAL /
  `chapter N`，这几种形态一条都匹不上。

加规则的代价是全库 7681 本的误报面，所以三条都是**先量后加**：新表相对旧表只有
**24 本**书换了规则（`pick_rule` 的选择变了），没有一本书的 `n_ok` 下降；24 本里 23 本
逐条读过原文确认变好（多数是"几十个巨型节点 → 几百个真标题"），1 本变差，
原因与代价记在第 9 条的注释里。

### 为什么"整行只有一个序号"必须 opt-in

有一批书的章节标题**就是**一行一个裸序号（`一`、`壹`、`　　1` 这样逐行往下数）。但同一个
形态在更多书里是**章内小节**的分节号：`第N章 标题` 下面再分 `1` `2` `3`。

把第 13 条默认打开，全库有 55 本书换规则，逐本读过原文之后是 **16 本变好 / 39 本变坏**。
变坏的书里，带标题的章（`第N章 标题（1）` 一类）被数量更多的 `1`/`2`/`3` 取代，有的
还会切出巨型节点。

关键是**没有任何行级特征能分开这两类**——缩进、序号字形、命中密度、与原规则的差额，
四项全部重叠（变好与变坏两组的差额区间大面积交叠）。区别是**书级**的：这本书还有没有
别的章节标记。评分器只看单条规则的命中分布，表达不了这件事。所以这条规则进表但默认关闭，
需要它的书在本机覆盖表（`scripts/toc-overrides.local.json`）里逐本点名——那张表就是为
这种"规则对、但只对某些书对"的情形存在的。

## 不变量

- `RULES` 的 `name` 唯一——它会被写进 `_toc.json` 的 `tocRule` 字段，也是覆盖表的键。
- 每条规则的 `example` 必须能被这条规则自己匹配（`scripts/tests/test_toc_rules.py` 断言）。
- 同一个单位字在 `UNIT` 与 `_VOL` 里受**同一份**约束（两条规则都会匹 `第N集`/`第N篇`/
  `第N部`，只改一边必然漂移）。由 `_guarded()` 这一个入口保证，测试钉住。

## 规则挡不住的那一半

后缀白名单管的是"单位字后面长得像不像标题"，它看不见**整本书的排版习惯**。
"同一本书里真标题顶格、正文行缩进两个全角空格"这条判据是按书统计出来的，
所以落在 `toc.filter_prose_hits`（一个纯函数，按书自适应），不在这张表里。
两者是互补的：白名单挡掉"没有分隔符的长句"，过滤器挡掉"带了分隔符的句子"。

这张表也管不了**"这本书还有没有别的章节标记"**——那是"纯序号行为什么必须 opt-in"
的根因。同族的另一半（"这些命中覆盖了多少篇幅"）已经不在这里了：第 9 条注释里记的
那一本回退（一串真标题只覆盖书尾的附录）由 `toc.Coverage` 那道篇幅门槛接住，
它是书级的度量，与单行正则无关。两者都需要跨规则/跨篇幅的判断，记在这里免得下一个人
再花一轮实测重新发现。
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from typing import Dict, Optional, Tuple

__all__ = [
    'NUM',
    'RULES',
    'RULES_BY_NAME',
    'SPECIAL',
    'TocRule',
    'UNIT',
    'by_name',
]


@dataclass(frozen=True)
class TocRule:
    """一条具名章节规则（design §4.3）。"""

    name: str
    """规则名。写入 `_toc.json` 的 `tocRule`，也是本机覆盖表（`toc-overrides.local.json`）的取值；须唯一。"""

    pattern: re.Pattern[str]
    """编译好的正则。行首/行尾空白由它自己吸收，见模块 docstring 的输入契约。"""

    enabled: bool = True
    """是否参与自动择一。激进规则为 `False`，只能被覆盖表显式点名。"""

    decorative: bool = False
    """这条规则匹出来的"标题"可能整行都是装饰符号，本身不含任何可读文本。

    为真的规则**不允许靠命中数取代已经选中的精确规则**（`toc.pick_rule`，需求 8.4）。
    理由与全库实测见下面第 10 条「符号装饰」自己的注释；这里只放一句结论：
    分场分隔线在结构上必然比章节多，按命中数硬比就必然是它赢。

    只标在规则上、不看单条命中的内容，是因为全库 7681 本里**没有一本**书让
    「符号装饰」靠"带真标题的命中"赢过精确规则（34 本选中它的书，其"有效章节"命中里
    含可读文本的条数分别是 0 × 33 本、1 × 1 本）。按内容逐条判（只让含汉字/拉丁字母/
    数字的命中参与取代比较）与按规则标记，在全库上给出**逐本相同**的结果，
    所以取代价更低的那一种：规则表本来就知道哪条规则的标题是装饰。
    """

    example: str = ''
    """一条能被本规则匹配的示例行。既是文档，也是回归断言的数据。"""

    def match(self, line: str) -> Optional[re.Match[str]]:
        """在**一行原文**上匹配。

        Args:
            line: 去掉行终止符、其余原样保留的一行（`str.splitlines()` 的产物）。
                不要预先 `strip()`——缩进是第 14 条的判据。

        Returns:
            命中的 `re.Match`，未命中为 `None`。
        """
        return self.pattern.match(line)


