# 共享片段
#
# design §4.3 指定了 NUM / UNIT / SPECIAL 三个公开片段，其余带 `_` 前缀的是本文件
# 内部的排版噪声补丁（缩进、分隔符、装饰符号），不构成对外契约。
# ---------------------------------------------------------------------------

#: 序号字符：ASCII 数字、全角数字、中文小写与大写数字。
#: 用法恒为 `NUM + '{1,8}'`——8 位足够 `一千二百四十五` 这类写法，也挡住了把一整串
#: 数字（电话号、年份表格）当序号的情况。
NUM = r'[0-9０-９〇零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]'

#: `NUM` 再加上白圈 `○`（U+25CB）。有些排版用它代替 `〇` 当"零"这个数位：
#: 有书的 `〔N〕标题` 里有一批写成 `〔一○○〕标题`、`〔二五○〕标题` 这样的形态，
#: 也有书写 `第三○○回`。
#:
#: **只在"序号前面有 `第` 或者左括号顶着"的位置用它**，不进 `NUM`：`○` 同时是
#: `_MARK` 里的装饰符号（`○○○` 是分场分隔线），把它放进全局 `NUM` 会让第 11 条
#: 「书名 序号」把 `甲乙丙○○○` 一类装饰行当标题。实测这个取舍是免费的——
#: 全库只有 2 本书用 `○` 当数位，加了之后 7681 本一本都没换规则、
#: 也没有一本的 `n_ok` 下降，只有那 2 本各多认了一批真标题。
_NUM_O = r'[0-9０-９〇○零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]'

#: 不带序号的特殊章节名。`正文(?!完|结)` 排除"正文完/正文结束"这类收尾行。
#: 注意 `序[章言]?` 允许裸 `序`，所以引用它的规则**必须**要求其后是分隔符或行尾，
#: 否则 `序列号是……` 一类正文行会被吞掉（见第 4 条的 `_TAIL_SEP`）。
SPECIAL = (
    r'(?:正文(?!完|结)'
    r'|序[章言]?'
    r'|楔子'
    r'|引子'
    r'|尾声'
    r'|终章'
    r'|后记'
    r'|番外'
    r'|外传'
    r'|前言)'
)

#: 行首：**锚点 + 允许的缩进**。锚点写进片段里，使每条规则都自带 `^`——
#: 即便有人用 `search()` 而不是 `match()`，也不会从行中间匹出标题。
#: `{0,4}` 取自 Legado 的经验值：排版缩进最多两个全角空格（4 个半角），再多就不是
#: 缩进而是居中对齐的装饰行了。含全角空格 U+3000——中文 txt 的主流缩进。
_HEAD = r'^[ \t\u3000]{0,4}'

#: 词间/行尾空白。含 `\r` 是对"按 `split('\n')` 切 CRLF 文本"的容错（见输入契约）。
_PAD = r'[ \t\u3000\r]*'

#: 序号与标题之间的分隔符（单个字符）。
_SEP = r'[ \t\u3000:：,，、.．_\-—–~～]'

#: 给中文数字用的**窄**分隔符：去掉 `,，:：`。正文里"一，""十："比"一、"更常见，
#: 用宽集合会让第 6 条在对话密集的书上刷出大量误报。`：` 自己另起一条规则
#: （第 7 条「大写数字 冒号 标题」），这样第 6 条的命中分布不受影响。
_SEP_CN = r'[ \t\u3000、.．_\-—–]'

#: 标题正文的长度上界。40 字符足够容纳"主标题 副标题"，又远短于正常段落。
_TITLE = r'.{0,40}'
_TITLE_REQ = r'.{1,40}'

#: 序号之后直到行尾：标题可有可无，`.` 会顺带吃掉行尾空白。
_TAIL = _TITLE + _PAD + r'$'

#: 同上，但要求标题前有分隔符。给"标记本身可能是正文词汇"的规则用（第 3、10 条）。
_TAIL_SEP = r'(?:' + _SEP + _PAD + _TITLE + r')?' + _PAD + r'$'

#: 成对装饰符的左半。右半由 `_TITLE` 顺带吃掉——很多书只写左半（`【第一章 标题`）。
#: 除第 9 条「括号装饰」外，`_UNIT_TAIL` 也用它——"单位字后面紧跟一个开符号"是
#: 标题的形态之一（`第十卷（终卷） 归途 第一章 …`、`第二卷【灯下青石】`）。
_OPEN = r'[【〖〔「『〈《（\[(]'

#: 成对装饰符的右半。只有第 9 条的裸序号分支与第 13 条用它，用途是"序号到这里结束"，
#: 所以不要求与 `_OPEN` 真正配对——`〔二八〕` 与 `【001】` 用的括号种类本来就混着来，
#: 数一个闭符号就够把 `（一个人站在那里）` 挡在门外了（`个` 既不是闭符号也不是分隔符）。
_CLOSE = r'[】〗〕」』〉》）\])]'

#: 标题的首字符必须是汉字或拉丁字母。第 9 条的裸序号分支靠这一条把
#: `【1.1】`（有书用它当章内小节号）挡掉：那一行会被读成
#: 序号 `1` + 分隔符 `.` + 标题 `1】`，而标题不许以数字开头。
_TITLE_HEAD = r'[\u4e00-\u9fffA-Za-z]'


# ---------------------------------------------------------------------------
# 章节单位与它的后缀白名单（design §4.3）
#
# 这是整张表最值钱、也最容易写错的部分。旧版给每个单位字挂一张**后继字黑名单**
# （`节(?!课)`、`场(?![和合比电是])`、`幕` 干脆不设防…），于是任何
# `第N{节,场,篇,幕,部,卷}…。` 形态的叙述句都成了章节。7681 本库抽检 100 本实测约
# 3400 个伪边界：受害最重的几本书里，将近一半的节点是正文，触发单位集中在
# 节 / 场 / 幕；同一批样本里 `章` 产出的正文误报是 **0**。六个字的黑名单分不出标题和
# 句子——句子的后继字是开放集合，黑名单永远补不齐。
#
# 改法：不再问"后面**不是**哪几个字"，而是要求后面**是**标题该有的形状。
# ---------------------------------------------------------------------------

#: 单位字与标题之间的分隔符。是 `_SEP` 去掉 `,，`、补上 `·－` 的版本：
#:
#: - 去掉逗号，因为它是正文最常见的形态而不是标题的形态。实测 7681 本产物里
#:   `第N场` 的后继字第一名就是 `，`（2133 次，形如
#:   `第二场，客队开局连丢十一分，看台上嘘声四起。`），
#:   `节`/`幕`/`篇` 的 `，` 也各有 763 / 114 / 67 次，基本全是正文；
#: - 补上 `·－`，因为 `第N章·N`（904 次）、`第N卷－标题`（10 次）
#:   是真标题的写法，而 `_SEP` 当初漏了这两个全角连接符。
_SEP_UNIT = r'[ \t\u3000:：、.．_\-—–~～·－]'

#: 句读点。出现在"单位字后面那截短尾巴"里就说明这一行是句子而不是标题。
#: `、` 也算在内：它是分隔符（`第N章、标题` 这种写法全库 22020 次），交给 `_SEP_UNIT`
#: 那一档处理，不该再被短尾巴吃进去。
_NO_SENT = r'[^，。！？；…,、]'

#: 短尾巴的字数上界。**6 是实测下来能挡住全部已知正文陷阱的最大值**：
#: `test_toc_rules.py::UNIT_TRAPS` 收的正文陷阱里，尾巴最短的是 7 个字（形如
#: `第四回合过后她已力竭` 的 `合过后她已力竭`），其余都不少于 8 个字；放到 8 就会把
#: `第五部分的证明放到附录`、`第九篇抄在黑板上的通知` 这种 8 个字的尾巴一起放进来。
#: 往下收到 4 则全库少认 145 条命中，其中有书全书只有寥寥几条 `第N篇章 标题`
#: （尾巴恰好 6 个字），少一个字这本书就整本退回兜底。所以取 6。
_UNIT_TAIL_MAX = 6

#: **单位字的后缀白名单**：单位字后面必须是下面两种形状之一。
#:
#: ① 一个分隔符——之后的标题长度不限（`第061节 雨夜访客`、`第002章：初到青石巷`）；
#: ② 至多 `_UNIT_TAIL_MAX` 个不含句读点的字符，然后就**行尾**或者一个**开符号**。
#:    这一档同时覆盖三种真实形态：裸编号（`第512章`、`第二百零九节` 这种写法全库共 3207 次）、
#:    漏了分隔符的短标题（`第十二节无人的车站`、`第一部小结`、`第三回合 七十二`）、
#:    以及装饰符号直接顶上来的标题（`第二卷【灯下青石】`）。
#:
#: 为什么②必须存在：拿掉它（只留分隔符/行尾/开符号）全库要少认 524 条命中、影响
#: 109 本书，其中有书会直接退回全书兜底，还有一本百万字符级的书只剩个位数的
#: 命中——等于没有目录。这几本的章节形态就是"单位字直接接短标题"：`第N回合 标题`、
#: `第N部分 标题`、`第N幕标题（附注）`。
#:
#: 那本百万字符级的书还顺带被②修好了：旧的 `回(?![合来事去])` 恰好把它全书的
#: `第N回合 标题` 全否了，这本书原先只切出寥寥几个节点（几乎全是超长章兜底的碎片），
#: 现在每个回合都有自己的节点。
#:
#: 反例也记一笔：有书的 `第N部分 标题`（旧 `部(?![分赛游门落])` 同样全否）
#: 在②之下恢复了，但那本书的择一结果本来就是「数字 分隔符 标题」，
#: 所以②对它没有可见影响——规则变好不等于产物变好，这两件事要分开看。
#:
#: 为什么②要卡死字数和句读点：叙述句要么带句读点，要么长。两个条件一起才够——
#: `第三幕终于开场。` 靠句读点挡，`第27节课讲的公式她一个都没记住` 靠字数挡。
_UNIT_TAIL = (
    r'(?:' + _SEP_UNIT
    + r'|' + _NO_SENT + r'{0,' + str(_UNIT_TAIL_MAX) + r'}'
    + r'(?:' + _PAD + r'$|' + _OPEN + r')'
    + r')'
)


def _guarded(units: str) -> str:
    """把若干单位字包成"字符类 + `_UNIT_TAIL` 先行断言"。

    做成函数而不是手写两遍，是为了让 `UNIT` 与 `_VOL` 对**同一个单位字**天然套用
    同一份约束。第 1、2 条都会匹 `第N集` / `第N篇` / `第N部` / `第N卷`，两边的约束
    若只改了一处，被漏的那条就会把 `第三集团的人马已经到了…` 一类正文行当标题——
    旧版的 `集(?![合和])` 就漏过 `团`，实测有书命中。
    `test_toc_rules.py::test_vol_and_unit_agree_on_the_same_unit_chars`（行为）与
    `::test_vol_and_unit_are_built_from_the_same_guard`（结构）一起钉住这条。

    用先行断言而不是直接消费字符，是因为约束要能和后面的 `_TAIL` 叠加：`_TAIL`
    还要把整个标题（含分隔符）一起吃掉。
    """
    return r'[' + units + r'](?=' + _UNIT_TAIL + r')'


#: 后缀白名单**不**适用的单位字。
#:
#: - `章`：全库 603 万条 `第N章` 标题里有 24443 条是"直接接标题、没有分隔符"的真标题
#:   （形如 `第0127章雨停了！`、`第一百零三章我只是路过`），而抽检样本里 `章` 的正文
#:   误报是 0。给它加约束是纯亏。
#: - `卷`：1295 条无分隔符标题里绝大多数是"卷名 + 章号"的复合长标题，长度远超②那
#:   6 个字的上界（形如 `第一卷少年远行 第一章 雨夜`、`第五卷三章 灯下旧事`：有书全书
#:   几百条都是这种写法，另有 15 本各数条 `第三卷青石旧事`）。
#:   实测给 `卷` 加上白名单要少认 927 条命中、影响 157 本书，其中有书整本退回兜底；
#:   换来的正文误报全库只有 1 条（一句以 `第N卷` 开头、讲述那一卷内容的叙述句）。那一条交给
#:   `toc.filter_prose_hits` 的按书自适应过滤——它缩进、又是句子形，正好是那层的靶子。
_UNIT_FREE = '章卷'

#: 后缀白名单**适用**的单位字：日常量词用法压倒章节用法的那一批。
#:
#: `夜` 与 `萌` 是后来补的两个"生僻但完全规整"的章节单位：
#:
#: - `夜`：有书全书几十条 `第N夜 标题`，补之前这本书选中的是「数字 分隔符 标题」，
#:   靠作者后记里几条 `1.注释正文…` 形态的条目切出寥寥几个节点，节点长度极不均匀。
#: - `萌`：有书全书上千条 `第N萌、标题`（序号一路写到四位数），补之前这本几百万字符的书
#:   **整本走全书兜底**，所有标题全是 `第 N 部分`。
#:
#: 代价实测为零：这两个字让全库 7681 本多认 347 条命中，其中 342 条就在上面那两本书里；
#: 剩下 5 条散在 4 本书，每本 1 条，而那 4 本各有几百条 `第N章` 真命中，`n_ok` 一条都没动。
#: 那 5 条里 4 条是正文（`第N夜、人名、人名，…` 这种以序数开头的叙述句，或者 `第N夜` 后面
#: 直接接名词的句子），顶格派的书里还会被 `toc.filter_prose_hits` 再筛一道。
#:
#: `日` / `天` / `扇` **刻意不收**，连带后缀白名单也不收——这是项目负责人拍板的决定：
#: `第二天清早她出门…`、`第一天报到…` 是遍布全库的日常叙述，而后缀白名单挡不住
#: `第一天 报到` 这种"序号 + 空格 + 短词"的正文行，误报面是整个书库；受益的只有 4 本书
#: （三本用 `第N日` / `第N天`，一本用 `第N扇…`——`扇` 同理是日常量词——各几条到几十条）。
#: 这 4 本**有意**留在全书兜底（约 5000 字符一块），这就是接受的结果，不是待修的漏网。
#: `test_toc_rules.py::test_day_units_are_never_chapter_headings`（行级）与
#: `test_toc_floor.py::test_day_unit_headings_leave_the_book_on_fallback`（合成书）一起钉住它。
_UNIT_GUARDED = '节回集部篇场幕话折夜萌'

#: 章节单位。`_UNIT_FREE` 的字裸放，`_UNIT_GUARDED` 的字带后缀白名单。
UNIT = r'(?:[' + _UNIT_FREE + r']|' + _guarded(_UNIT_GUARDED) + r')'

#: 卷级单位字，按"是否带后缀白名单"分成两半，与 `_UNIT_FREE` / `_UNIT_GUARDED` 对齐。
#: `章` 不在此列——第 2 条只管卷/部/册/集/篇；`册` 只在此列，`UNIT` 里没有它。
_VOL_FREE = '卷'
_VOL_GUARDED = '部册集篇'

#: `第N卷` 位置上的卷级单位。与 `UNIT` 共用 `_guarded`，所以 `部`/`集`/`篇` 在第 1、2
#: 两条规则上的约束逐字相同。
_VOL = r'(?:[' + _VOL_FREE + r']|' + _guarded(_VOL_GUARDED) + r')'

#: `卷五 归途` 位置上的**裸**卷级单位字：它的后继是序号而不是标题，
#: 套 `_UNIT_TAIL` 会把 `卷五 …` 整类形态一起否掉。
_VOL_BARE = r'[' + _VOL_FREE + _VOL_GUARDED + r']'

#: 第 3 条「单位 序号」认的单位字：`章一 标题`、`段三一 标题` 这种**单位字在前、
#: 序号在后**的写法。卷级的那几个字不在此列——第 2 条的 `_VOL_BARE` 已经管了 `卷三 …`。
#:
#: **只有这两个字，是量出来的结论**。全库 7681 本里 `章`/`段` 这个形态一共命中 1776 行，
#: 其中 1775 行是 6 本书的真标题：这几本书原先只切出几十个节点（几乎全是超长章兜底的
#: 碎片），补上第 3 条之后每个 `段N 标题` / `章N 标题` 都成了一个节点。
#:
#: 剩下那 1 行是一本书里的叙述句：`段一` 恰好是句首人名的前两个字，后面两个字接一个
#: 开符号 `《`（形如 `　　段一某在《片名》里演一个配角，……。`），正好落在 `_UNIT_TAIL`
#: 的②档里。那本书有几百条 `第N章` 真命中，这 1 行既不改变规则选择、
#: 也会被 `toc.filter_prose_hits` 按"缩进 + 句子形"筛掉。
#:
#: 把单位集扩成 `章段回节话折幕场夜` 之后，全库只多出 25 条命中、散在 13 本书，
#: **一条真标题都没有**，全是正文：`夜一：` 后面接一句台词（`夜一` 是个角色名）、
#: `折一千只纸船`、`夜21:40，她推开了阁楼的窗。` 这类。
#: 这 13 本一本都没换规则（它们各有几百条 `第N章`），但那 25 条是白送的误报面，
#: 所以宽集合被否掉。
#:
#: 与 `第N夜`（在 `_UNIT_GUARDED` 里）的差别值得记一笔：`第` 这个字本身就是强锚点，
#: 而 `夜一`/`折一` 少了它，`_UNIT_TAIL` 的分隔符那一档（`：`/`、` 之后标题不限长）
#: 就成了漏洞——同一个后缀白名单，锚点强度不同，安全性就不同。
_UNIT_LEAD = r'[章段]'

#: 纯中文数字 / 纯阿拉伯（含全角）数字，第 5、6 条要分开对待。
_CNUM = r'[〇零一二两三四五六七八九十百千万壹贰叁肆伍陆柒捌玖拾佰仟]'
_ANUM = r'[0-9０-９]'

#: 第 13 条「纯序号行」里"整行就是这个"的序号本体。两档分开写而不是用 `NUM`：
#: 阿拉伯数字卡在 3 位（`2010` 独占一行时是年份而不是章号），中文数字放到 8 位
#: （`一千二百四十五` 也只有 7 个字）。
_NUM_LINE = r'(?:' + _CNUM + r'{1,8}|' + _ANUM + r'{1,3})'

#: 单个装饰符号（晋江系常见）。
_MARK = r'[☆★✦✧◆◇○●◎※＊]'

#: 拉丁章节词。`no` 必须带标点（`No.4`），否则 `No matter …` 一类正文行会被误判。
_LATIN = r'(?:chapter|section|part|ＰＡＲＴ|episode|no[.．、])'


